module top_2D_DCT (
    input clk, rstn
);

    wire [16*8-1:0] x_in;
    wire [16*12-1:0] x_out;

    reg [14-1:0] counter;

    always @(posedge clk or negedge rstn) begin
        if(!rstn) begin counter <= 14'd0; end
        else counter <= counter + 14'd1;
    end

    wire [14-1:0] counter_in, counter_out;
    assign counter_in = counter;
    assign counter_out = counter - 14'd35;

    wire [16*8-1:0] DIN;
    wire [16*12-1:0] DO;
    reg running;
    always @(posedge clk or negedge rstn) begin
        if (!rstn)
            running <= 1'b0;
        else if (counter == 5'd0)   // 언더플로우 안 거치고 정상 0 도달
            running <= 1'b1;
    end

    rflp16384x128mx16 MEM_IN(.DO(x_in),.DIN(DIN),.CLK(clk),.RA(counter_in[13:4]),.CA(counter_in[3:0]),.NWRT(1'b1),.NCE(1'b0));

    DCT_2D DCT(clk, rstn, x_in, x_out, counter[4:0], running);

    rflp16384x192mx16 MEM_OUT(.DO(DO),.DIN(x_out),.CLK(clk),.RA(counter_out[13:4]),.CA(counter_out[3:0]),.NWRT(1'b0),.NCE(1'b0));

endmodule

module top_2D_DCT_synth (
    input clk, rstn
);

    wire [16*8-1:0] x_in;
    wire [16*12-1:0] x_out;

    reg [14-1:0] counter;

    always @(posedge clk or negedge rstn) begin
        if(!rstn) begin counter <= 14'd0; end
        else counter <= counter + 14'd1;
    end

    wire [14-1:0] counter_in, counter_out;
    assign counter_in = counter;
    assign counter_out = counter - 14'd35;

    wire [16*8-1:0] DIN;
    wire [16*12-1:0] DO;
    reg running;
    always @(posedge clk or negedge rstn) begin
        if (!rstn)
            running <= 1'b0;
        else if (counter == 5'd0)   // 언더플로우 안 거치고 정상 0 도달
            running <= 1'b1;
    end

    D_FF128 D_IN(.q(x_in),.d(),.clk(clk), .rstn(rstn));

    DCT_2D DCT(clk, rstn, x_in, x_out, counter[5-1:0]);

    D_FF192 D_OUT(.q(),.d(x_out),.clk(clk), .rstn(rstn));

endmodule

module DCT_2D (
    input clk, rstn,
    input [16*8-1:0] x_in, 
    output [16*12-1:0] x_out,
    input [5-1:0] counter,
    input running
);

    localparam DCT_1st_res_BW = 11;
    localparam coeffi_quant = 8;

    ///////////////////////////////////////////////////////////////////
    ///////////////////////     coefficient     ///////////////////////
    ///////////////////////////////////////////////////////////////////
    wire signed [coeffi_quant-1:0] c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15;

    // 16-point DCT-II unique coefficients, Q1.7 signed (sign + 7 frac bits)
    //   c_k = (1/sqrt(8)) * cos(k*pi/32),  k = 1..15   (a..o)
    //   stored as positive magnitudes (MSB=0); sign is applied by the
    //   surrounding add/sub matrix structure.  (generated by
    //   gen_DCT_coeffi_verilog.m)
    //   coefficient -> (8.7)
    assign c1  = 8'h2D;  // a = 0.351851 -> 0.351562 (err -0.000288) 
    assign c2  = 8'h2C;  // b = 0.346760 -> 0.343750 (err -0.003010)
    assign c3  = 8'h2B;  // c = 0.338330 -> 0.335938 (err -0.002392)
    assign c4  = 8'h2A;  // d = 0.326641 -> 0.328125 (err +0.001484)
    assign c5  = 8'h28;  // e = 0.311806 -> 0.312500 (err +0.000694)
    assign c6  = 8'h26;  // f = 0.293969 -> 0.296875 (err +0.002906)
    assign c7  = 8'h23;  // g = 0.273300 -> 0.273438 (err +0.000138)
    assign c8  = 8'h20;  // h = 0.250000 -> 0.250000 (err +0.000000)
    assign c9  = 8'h1D;  // i = 0.224292 -> 0.226562 (err +0.002270)
    assign c10 = 8'h19;  // j = 0.196424 -> 0.195312 (err -0.001111)
    assign c11 = 8'h15;  // k = 0.166664 -> 0.164062 (err -0.002601)
    assign c12 = 8'h11;  // l = 0.135299 -> 0.132812 (err -0.002487)
    assign c13 = 8'h0D;  // m = 0.102631 -> 0.101562 (err -0.001069)
    assign c14 = 8'h09;  // n = 0.068975 -> 0.070312 (err +0.001337)
    assign c15 = 8'h04;  // o = 0.034654 -> 0.031250 (err -0.003404)

    ///////////////////////////////////////////////////////////////////
    ///////////////////////////     DCT     ///////////////////////////
    ///////////////////////////////////////////////////////////////////

    wire [16*DCT_1st_res_BW-1:0] DCT_1st_out;

    //16x8bit
    DCT_1D_1st #(.BW(DCT_1st_res_BW)) DCT_1st(x_in, DCT_1st_out, c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15);
    //DCT_1st out : 16x12(1D-DCT_res_qunatization)bit

    wire o_en1, o_en2;
    wire [16*DCT_1st_res_BW-1:0] TPmem_out1, TPmem_out2;
    wire [16*12-1:0] TPmem_out3, TPmem_out4;

    wire [5-1:0] counter_TP12 = counter - 5'd1;


    TPmem_16x16 #(.BW(DCT_1st_res_BW)) TP_MEM_1(.i_data(DCT_1st_out), .i_enable(running&!counter_TP12[4]), 
                        .i_clk(clk), .i_Reset(rstn), .o_data(TPmem_out1), .o_en(o_en1));
    TPmem_16x16 #(.BW(DCT_1st_res_BW)) TP_MEM_2(.i_data(DCT_1st_out), .i_enable(running&counter_TP12[4]), 
                        .i_clk(clk), .i_Reset(rstn), .o_data(TPmem_out2), .o_en(o_en2));
    //TP_mem out : 16x(DCT_1st_res_BW)bit

    wire [16*DCT_1st_res_BW-1:0] x_in2 = (TPmem_out1 | TPmem_out2);
    wire [16*12-1:0] x_out2;
    wire is_dc = (counter_TP12[3:0] == 1);

    //DCT_2nd_in : 16x(DCT_1st_res_BW)bit
    DCT_1D_2nd #(.SIGNED_IN(1),.input_BW(DCT_1st_res_BW),.coeffi_quant(8), .BW(12)) DCT_2st(x_in2, x_out2, c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15, is_dc);

    //DCT_2nd_out : 16x12(trunc)bit
    TPmem_16x16 #(.BW(12)) TP_MEM_3(.i_data(x_out2), .i_enable(o_en1), 
                        .i_clk(clk), .i_Reset(rstn), .o_data(TPmem_out3), .o_en());
    TPmem_16x16 #(.BW(12)) TP_MEM_4(.i_data(x_out2), .i_enable(o_en2), 
                        .i_clk(clk), .i_Reset(rstn), .o_data(TPmem_out4), .o_en());

    assign x_out = TPmem_out3 | TPmem_out4;



    ///debugging
    // ===== 1D-DCT 결과 lane별 분리 (파형 디버그용, signed decimal로 보기) =====
    //  DCT_1st_out = { y0, y1, ..., y15 }  (y0 = MSB)
    //  각 계수 11bit, 총 176bit
    wire signed [10:0] s1_y0  = DCT_1st_out[176-1  -: 11];   // [175:165]
    wire signed [10:0] s1_y1  = DCT_1st_out[165-1  -: 11];   // [164:154]
    wire signed [10:0] s1_y2  = DCT_1st_out[154-1  -: 11];   // [153:143]
    wire signed [10:0] s1_y3  = DCT_1st_out[143-1  -: 11];   // [142:132]
    wire signed [10:0] s1_y4  = DCT_1st_out[132-1  -: 11];   // [131:121]
    wire signed [10:0] s1_y5  = DCT_1st_out[121-1  -: 11];   // [120:110]
    wire signed [10:0] s1_y6  = DCT_1st_out[110-1  -: 11];   // [109:99]
    wire signed [10:0] s1_y7  = DCT_1st_out[99 -1  -: 11];   // [98:88]
    wire signed [10:0] s1_y8  = DCT_1st_out[88 -1  -: 11];   // [87:77]
    wire signed [10:0] s1_y9  = DCT_1st_out[77 -1  -: 11];   // [76:66]
    wire signed [10:0] s1_y10 = DCT_1st_out[66 -1  -: 11];   // [65:55]
    wire signed [10:0] s1_y11 = DCT_1st_out[55 -1  -: 11];   // [54:44]
    wire signed [10:0] s1_y12 = DCT_1st_out[44 -1  -: 11];   // [43:33]
    wire signed [10:0] s1_y13 = DCT_1st_out[33 -1  -: 11];   // [32:22]
    wire signed [10:0] s1_y14 = DCT_1st_out[22 -1  -: 11];   // [21:11]
    wire signed [10:0] s1_y15 = DCT_1st_out[11 -1  -: 11];   // [10:0]

    wire signed [11:0] s2_y0  = x_out2[192-1  -: 12];   // [175:165]
    wire signed [11:0] s2_y1  = x_out2[180-1  -: 12];   // [164:154]
    wire signed [11:0] s2_y2  = x_out2[168-1  -: 12];   // [153:143]
    wire signed [11:0] s2_y3  = x_out2[156-1  -: 12];   // [142:132]
    wire signed [11:0] s2_y4  = x_out2[144-1  -: 12];   // [131:121]
    wire signed [11:0] s2_y5  = x_out2[132-1  -: 12];   // [120:110]
    wire signed [11:0] s2_y6  = x_out2[120-1  -: 12];   // [109:99]
    wire signed [11:0] s2_y7  = x_out2[108 -1  -: 12];   // [98:88]
    wire signed [11:0] s2_y8  = x_out2[96 -1  -: 12];   // [87:77]
    wire signed [11:0] s2_y9  = x_out2[84 -1  -: 12];   // [76:66]
    wire signed [11:0] s2_y10 = x_out2[72 -1  -: 12];   // [65:55]
    wire signed [11:0] s2_y11 = x_out2[60 -1  -: 12];   // [54:44]
    wire signed [11:0] s2_y12 = x_out2[48 -1  -: 12];   // [43:33]
    wire signed [11:0] s2_y13 = x_out2[36 -1  -: 12];   // [32:22]
    wire signed [11:0] s2_y14 = x_out2[24 -1  -: 12];   // [21:11]
    wire signed [11:0] s2_y15 = x_out2[12 -1  -: 12];   // [10:0]

endmodule


module DCT_1D_1st
#(
    parameter input_BW    = 8,
    parameter BW          = 12,
    parameter coeffi_quant = 8,
    parameter SIGNED_IN   = 0   // 0: unsigned input (1st DCT, 0~255 zero-extend)
                                // 1: signed   input (2nd DCT, sign-extend)
)
(   input  [16*input_BW-1:0] x_in,
    output [16*BW-1:0]       x_out,
    input  signed [coeffi_quant-1:0] c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15
);

    localparam W = input_BW + coeffi_quant + 2; // full-precision y width (= 18 @ 8/8)

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////               x preparation                ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [input_BW+1-1:0] x0,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15;

    // [FIX 1] extend bit = (unsigned)? 0 : MSB(sign)
    //   1st DCT (SIGNED_IN=0): unsigned 0~255 -> zero-extend
    //   2nd DCT (SIGNED_IN=1): signed DCT coef -> sign-extend
    assign x15  = {SIGNED_IN ? x_in[input_BW*1 -1] : 1'b0, x_in[input_BW*1 -1 : input_BW*0 ]};
    assign x0 = {SIGNED_IN ? x_in[input_BW*16-1] : 1'b0, x_in[input_BW*16-1 : input_BW*15]};

    assign x14  = {SIGNED_IN ? x_in[input_BW*2 -1] : 1'b0, x_in[input_BW*2 -1 : input_BW*1 ]};
    assign x1 = {SIGNED_IN ? x_in[input_BW*15-1] : 1'b0, x_in[input_BW*15-1 : input_BW*14]};

    assign x13  = {SIGNED_IN ? x_in[input_BW*3 -1] : 1'b0, x_in[input_BW*3 -1 : input_BW*2 ]};
    assign x2 = {SIGNED_IN ? x_in[input_BW*14-1] : 1'b0, x_in[input_BW*14-1 : input_BW*13]};

    assign x12  = {SIGNED_IN ? x_in[input_BW*4 -1] : 1'b0, x_in[input_BW*4 -1 : input_BW*3 ]};
    assign x3 = {SIGNED_IN ? x_in[input_BW*13-1] : 1'b0, x_in[input_BW*13-1 : input_BW*12]};

    assign x11  = {SIGNED_IN ? x_in[input_BW*5 -1] : 1'b0, x_in[input_BW*5 -1 : input_BW*4 ]};
    assign x4 = {SIGNED_IN ? x_in[input_BW*12-1] : 1'b0, x_in[input_BW*12-1 : input_BW*11]};

    assign x10  = {SIGNED_IN ? x_in[input_BW*6 -1] : 1'b0, x_in[input_BW*6 -1 : input_BW*5 ]};
    assign x5 = {SIGNED_IN ? x_in[input_BW*11-1] : 1'b0, x_in[input_BW*11-1 : input_BW*10]};

    assign x9  = {SIGNED_IN ? x_in[input_BW*7 -1] : 1'b0, x_in[input_BW*7 -1 : input_BW*6 ]};
    assign x6  = {SIGNED_IN ? x_in[input_BW*10-1] : 1'b0, x_in[input_BW*10-1 : input_BW*9 ]};

    assign x8  = {SIGNED_IN ? x_in[input_BW*8 -1] : 1'b0, x_in[input_BW*8 -1 : input_BW*7 ]};
    assign x7  = {SIGNED_IN ? x_in[input_BW*9 -1] : 1'b0, x_in[input_BW*9 -1 : input_BW*8 ]};

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////               s,d preparation              ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [input_BW+2-1:0] s0,s1,s2,s3,s4,s5,s6,s7;
    wire signed [input_BW+1-1:0] d0,d1,d2,d3,d4,d5,d6,d7;

    assign s0 = x0 + x15;  assign d0 = x0 - x15;
    assign s1 = x1 + x14;  assign d1 = x1 - x14;
    assign s2 = x2 + x13;  assign d2 = x2 - x13;
    assign s3 = x3 + x12;  assign d3 = x3 - x12;
    assign s4 = x4 + x11;  assign d4 = x4 - x11;
    assign s5 = x5 + x10;  assign d5 = x5 - x10;
    assign s6 = x6 + x9 ;  assign d6 = x6 - x9 ;
    assign s7 = x7 + x8 ;  assign d7 = x7 - x8 ;

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////                 y operation                ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [W-1:0] y0,y1,y2,y3,y4,y5,y6,y7,y8,y9,y10,y11,y12,y13,y14,y15;

    // 8-point odd part
    assign y1  =  c1*d0 +  c3*d1 +  c5*d2 +  c7*d3 +  c9*d4 + c11*d5 + c13*d6 + c15*d7;
    assign y15 = c15*d0 - c13*d1 + c11*d2 -  c9*d3 +  c7*d4 -  c5*d5 +  c3*d6 -  c1*d7;
    assign y3  =  c3*d0 +  c9*d1 + c15*d2 - c11*d3 -  c5*d4 -  c1*d5 -  c7*d6 - c13*d7;
    assign y13 = c13*d0 -  c7*d1 +  c1*d2 -  c5*d3 + c11*d4 + c15*d5 -  c9*d6 +  c3*d7;
    assign y5  =  c5*d0 + c15*d1 -  c7*d2 -  c3*d3 - c13*d4 +  c9*d5 +  c1*d6 + c11*d7;
    assign y11 = c11*d0 -  c1*d1 +  c9*d2 + c13*d3 -  c3*d4 +  c7*d5 + c15*d6 -  c5*d7;
    assign y7  =  c7*d0 - c11*d1 -  c3*d2 + c15*d3 +  c1*d4 + c13*d5 -  c5*d6 -  c9*d7;
    assign y9  =  c9*d0 -  c5*d1 - c13*d2 +  c1*d3 - c15*d4 -  c3*d5 + c11*d6 +  c7*d7;

    // 8-point even part : 2nd butterfly on s
    wire signed [input_BW+3-1:0] ss0, ss1, ss2, ss3;
    wire signed [input_BW+2-1:0] sd0, sd1, sd2, sd3;

    assign ss0 = s0 + s7;  assign sd0 = s0 - s7;
    assign ss1 = s1 + s6;  assign sd1 = s1 - s6;
    assign ss2 = s2 + s5;  assign sd2 = s2 - s5;
    assign ss3 = s3 + s4;  assign sd3 = s3 - s4;

    // 4-point odd part
    assign y2  =  c2*sd0 +  c6*sd1 + c10*sd2 + c14*sd3;
    assign y14 = c14*sd0 - c10*sd1 +  c6*sd2 -  c2*sd3;
    assign y6  =  c6*sd0 - c14*sd1 -  c2*sd2 - c10*sd3;
    assign y10 = c10*sd0 -  c2*sd1 + c14*sd2 +  c6*sd3;

    // 4-point even part : 3rd butterfly on ss
    wire signed [input_BW+4-1:0] sss0, sss1;
    wire signed [input_BW+3-1:0] ssd0, ssd1;

    assign sss0 = ss0 + ss3;  assign ssd0 = ss0 - ss3;
    assign sss1 = ss1 + ss2;  assign ssd1 = ss1 - ss2;

    // 2-point odd part
    assign y4  =  c4*ssd0 + c12*ssd1;
    assign y12 = c12*ssd0 -  c4*ssd1;

    // 2-point even part
    assign y0 = c8 * (sss0 + sss1);
    assign y8 = c8 * (sss0 - sss1);

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////              result truncation             ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    // [FIX 2] all 16 lanes use the SAME MSB-anchored window [W-1 : W-BW].
    //   - keeps sign + top BW bits, never wraps, no out-of-range for any BW<=W
    //   - same Q-format across every output lane
    assign x_out = { y0 [W-1:W-BW], y1 [W-1:W-BW], y2 [W-1:W-BW], y3 [W-1:W-BW],
                     y4 [W-1:W-BW], y5 [W-1:W-BW], y6 [W-1:W-BW], y7 [W-1:W-BW],
                     y8 [W-1:W-BW], y9 [W-1:W-BW], y10[W-1:W-BW], y11[W-1:W-BW],
                     y12[W-1:W-BW], y13[W-1:W-BW], y14[W-1:W-BW], y15[W-1:W-BW] };

endmodule


module DCT_1D_2nd
#(
    parameter input_BW    = 8,
    parameter BW          = 12,
    parameter coeffi_quant = 8,
    parameter SIGNED_IN   = 0   // 0: unsigned input (1st DCT, 0~255 zero-extend)
                                // 1: signed   input (2nd DCT, sign-extend)
)
(   input  [16*input_BW-1:0] x_in,
    output [16*BW-1:0]       x_out,
    input  signed [coeffi_quant-1:0] c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15,
    input is_dc
);

    localparam W = input_BW + coeffi_quant + 2; // full-precision y width (= 18 @ 8/8)

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////               x preparation                ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [input_BW+1-1:0] x0,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15;

    // [FIX 1] extend bit = (unsigned)? 0 : MSB(sign)
    //   1st DCT (SIGNED_IN=0): unsigned 0~255 -> zero-extend
    //   2nd DCT (SIGNED_IN=1): signed DCT coef -> sign-extend
    assign x15  = {SIGNED_IN ? x_in[input_BW*1 -1] : 1'b0, x_in[input_BW*1 -1 : input_BW*0 ]};
    assign x0 = {SIGNED_IN ? x_in[input_BW*16-1] : 1'b0, x_in[input_BW*16-1 : input_BW*15]};

    assign x14  = {SIGNED_IN ? x_in[input_BW*2 -1] : 1'b0, x_in[input_BW*2 -1 : input_BW*1 ]};
    assign x1 = {SIGNED_IN ? x_in[input_BW*15-1] : 1'b0, x_in[input_BW*15-1 : input_BW*14]};

