    ///////////////////////////////////////////////////////////////////
    ///////////////////////////     DCT     ///////////////////////////
    ///////////////////////////////////////////////////////////////////

    wire [16*DCT_1st_res_BW-1:0] DCT_1st_out;

    //16x8bit
    DCT_1D_1st_v6 #(.BW(DCT_1st_res_BW)) DCT_1st(x_in, DCT_1st_out, c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15);
    //DCT_1st out : 16x12(1D-DCT_res_qunatization)bit

    wire o_en1, o_en2;
    wire [16*DCT_1st_res_BW-1:0] TPmem_out1, TPmem_out2;
    wire [16*12-1:0] TPmem_out3, TPmem_out4;

    wire [5-1:0] counter_TP12 = counter - 5'd1;


