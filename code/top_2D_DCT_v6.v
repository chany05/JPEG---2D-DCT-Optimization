    //DCT_2nd_in : 16x(DCT_1st_res_BW)bit
    DCT_1D_2nd_v6 DCT_2st(x_in2, x_out2, c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15, is_dc, is_dc2);

    //DCT_2nd_out : 16x12(trunc)bit
    /*TPmem_16x16 #(.BW(12)) TP_MEM_3(.i_data(x_out2), .i_enable(o_en1), 
                        .i_clk(clk), .i_Reset(rstn), .o_data(TPmem_out3), .o_en());
