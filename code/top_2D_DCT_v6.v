                        .i_clk(clk), .i_Reset(rstn), .o_data(x_out), .o_en(o_en1));

    //assign x_out = TPmem_out3 | TPmem_out4;

    // ===== debug: per-lane signed split (ModelSim 파형용) =====
    wire signed [7:0] s1_y0  = DCT_1st_out[127 -: 8];
