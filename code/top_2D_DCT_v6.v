// =====================================================================
//  top_2D_DCT_v6  -  coefficient 6bit (6,5)=Q1.5, 1D-DCT result 8bit
//  derived from validated v5 (overflow-fixed) by code/gen_v6.py
//  - all rotation constants re-quantised Q1.7(x128) -> Q1.5(x32)
//  - 1D result / TPMEM_1 width 11->8 bit ; 2nd-stage output stays 12bit
//  - 2nd-stage trunc re-derived: AC=y[12:1], DC=y[14:3]
// =====================================================================

module top_2D_DCT_v6 (
    input clk, rstn
);

    wire [16*8-1:0] x_in;
    wire [16*12-1:0] x_out;

    reg [14-1:0] counter;

    always @(posedge clk or negedge rstn) begin
        if(!rstn) begin counter <= 14'd0; end
        else counter <= counter + 14'd1;
    end

    wire [14-1:0] counter_in, counter_out;
    assign counter_in = counter;
    assign counter_out = counter - 14'd35;

    wire [16*8-1:0] DIN;
    wire [16*12-1:0] DO;
    reg running;
    always @(posedge clk or negedge rstn) begin
        if (!rstn)
            running <= 1'b0;
        else if (counter == 5'd0)   // 언더플로우 안 거치고 정상 0 도달
            running <= 1'b1;
    end

    rflp16384x128mx16 MEM_IN(.DO(x_in),.DIN(DIN),.CLK(clk),.RA(counter_in[13:4]),.CA(counter_in[3:0]),.NWRT(1'b1),.NCE(1'b0));

    DCT_2D_v6 #(.coeffi_quant(6), .DCT_1st_res_BW(8)) DCT(clk, rstn, x_in, x_out, counter[4:0], running);

    rflp16384x192mx16 MEM_OUT(.DO(DO),.DIN(x_out),.CLK(clk),.RA(counter_out[13:4]),.CA(counter_out[3:0]),.NWRT(1'b0),.NCE(1'b0));

endmodule

module top_2D_DCT_synth_v6 (
    input clk, rstn
);

    wire [16*8-1:0] x_in;
    wire [16*12-1:0] x_out;

    reg [14-1:0] counter;

    always @(posedge clk or negedge rstn) begin
        if(!rstn) begin counter <= 14'd0; end
        else counter <= counter + 14'd1;
    end

    wire [14-1:0] counter_in, counter_out;
    assign counter_in = counter;
    assign counter_out = counter - 14'd35;

    wire [16*8-1:0] DIN;
    wire [16*12-1:0] DO;
    reg running;
    always @(posedge clk or negedge rstn) begin
        if (!rstn)
            running <= 1'b0;
        else if (counter == 5'd0)   // 언더플로우 안 거치고 정상 0 도달
            running <= 1'b1;
    end

    D_FF128_v6 D_IN(.q(x_in),.d(),.clk(clk), .rstn(rstn));

    DCT_2D_v6 DCT(clk, rstn, x_in, x_out, counter[5-1:0]);

    D_FF192_v6 D_OUT(.q(),.d(x_out),.clk(clk), .rstn(rstn));

endmodule

