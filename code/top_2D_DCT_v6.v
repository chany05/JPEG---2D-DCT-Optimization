    assign y2 = A_o4_y20+A_o4_y21;
    assign y3 = A_o8_y30+A_o8_y31+A_o8_y32+A_o8_y33;
    assign y4 = A_o2_y40;
    assign y5 = A_o8_y50+A_o8_y51+A_o8_y52+A_o8_y53;
    assign y6 = A_o4_y60+A_o4_y61;
    assign y7 = A_o8_y70+A_o8_y71+A_o8_y72+A_o8_y73;
    assign y9 = B_o8_y70+B_o8_y71+B_o8_y72+B_o8_y73;
    assign y10 = B_o4_y60+B_o4_y61;
    assign y11 = B_o8_y50+B_o8_y51+B_o8_y52+B_o8_y53;
    assign y12 = B_o2_y40;
    assign y13 = B_o8_y30+B_o8_y31+B_o8_y32+B_o8_y33;
    assign y14 = B_o4_y20+B_o4_y21;
    assign y15 = B_o8_y10+B_o8_y11+B_o8_y12+B_o8_y13;
    assign x_out = {y0[W-1:W-BW],y1[W-1:W-BW],y2[W-1:W-BW],y3[W-1:W-BW],y4[W-1:W-BW],y5[W-1:W-BW],y6[W-1:W-BW],y7[W-1:W-BW],y8[W-1:W-BW],y9[W-1:W-BW],y10[W-1:W-BW],y11[W-1:W-BW],y12[W-1:W-BW],y13[W-1:W-BW],y14[W-1:W-BW],y15[W-1:W-BW]};
endmodule

// 1D-DCT 2nd stage. input 8bit signed (1D result = floor(DCT_1d/8)), output 12bit.
//   y2 = DCT_2d*4 (s2=2).  DC(1,1)->y[14:3] (=DCT_2d/2) ; AC->y[12:1] (=DCT_2d*2)
// same re-quantised constants as 1st stage. output interface stays 12bit (Verilog_IO compat).
module DCT_1D_2nd_v6
#( parameter input_BW=8, parameter coeffi_quant=6, parameter SIGNED_IN=1 )
(   input  [16*input_BW-1:0] x_in,
    output [16*12-1:0]       x_out,
    input  signed [coeffi_quant-1:0] c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15,  // unused
    input is_dc, is_dc2
);
    localparam BW = 12;   // (unused by arith; arith uses input_BW/coeffi_quant)
    localparam W = input_BW + coeffi_quant + 2;
    //x_in할당 부분
    wire signed [input_BW+1-1:0] x0,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15;

    assign x15 = {SIGNED_IN ? x_in[input_BW*1-1] : 1'b0, x_in[input_BW*1-1 : input_BW*0]};
    assign x0 = {SIGNED_IN ? x_in[input_BW*16-1] : 1'b0, x_in[input_BW*16-1 : input_BW*15]};

    assign x14 = {SIGNED_IN ? x_in[input_BW*2-1] : 1'b0, x_in[input_BW*2-1 : input_BW*1]};
    assign x1 = {SIGNED_IN ? x_in[input_BW*15-1] : 1'b0, x_in[input_BW*15-1 : input_BW*14]};

    assign x13 = {SIGNED_IN ? x_in[input_BW*3-1] : 1'b0, x_in[input_BW*3-1 : input_BW*2]};
    assign x2 = {SIGNED_IN ? x_in[input_BW*14-1] : 1'b0, x_in[input_BW*14-1 : input_BW*13]};

    assign x12 = {SIGNED_IN ? x_in[input_BW*4-1] : 1'b0, x_in[input_BW*4-1 : input_BW*3]};
    assign x3 = {SIGNED_IN ? x_in[input_BW*13-1] : 1'b0, x_in[input_BW*13-1 : input_BW*12]};

    assign x11 = {SIGNED_IN ? x_in[input_BW*5-1] : 1'b0, x_in[input_BW*5-1 : input_BW*4]};
    assign x4 = {SIGNED_IN ? x_in[input_BW*12-1] : 1'b0, x_in[input_BW*12-1 : input_BW*11]};

    assign x10 = {SIGNED_IN ? x_in[input_BW*6-1] : 1'b0, x_in[input_BW*6-1 : input_BW*5]};
    assign x5 = {SIGNED_IN ? x_in[input_BW*11-1] : 1'b0, x_in[input_BW*11-1 : input_BW*10]};

    assign x9 = {SIGNED_IN ? x_in[input_BW*7-1] : 1'b0, x_in[input_BW*7-1 : input_BW*6]};
    assign x6 = {SIGNED_IN ? x_in[input_BW*10-1] : 1'b0, x_in[input_BW*10-1 : input_BW*9]};

    assign x8 = {SIGNED_IN ? x_in[input_BW*8-1] : 1'b0, x_in[input_BW*8-1 : input_BW*7]};
    assign x7 = {SIGNED_IN ? x_in[input_BW*9-1] : 1'b0, x_in[input_BW*9-1 : input_BW*8]};


    //s, d 할당 부분
    wire signed [input_BW+2-1:0] s0,s1,s2,s3,s4,s5,s6,s7;
    wire signed [input_BW+1-1:0] d0,d1,d2,d3,d4,d5,d6,d7;

    assign s0=x0+x15; assign d0=x0-x15;
    assign s1=x1+x14; assign d1=x1-x14;
    assign s2=x2+x13; assign d2=x2-x13;
    assign s3=x3+x12; assign d3=x3-x12;
    assign s4=x4+x11; assign d4=x4-x11;
    assign s5=x5+x10; assign d5=x5-x10;
    assign s6=x6+x9; assign d6=x6-x9;
    assign s7=x7+x8; assign d7=x7-x8;

    //odd 8 dct에서의 3mult의 t를 정의, 곱셈은 상수값으로 미리 계산해서함
    wire signed [input_BW+2-1:0] o8_sum0=d0+d7;
    wire signed [input_BW+2-1:0] o8_sum1=d1+d6;
    wire signed [input_BW+2-1:0] o8_sum2=d2+d5;
    wire signed [input_BW+2-1:0] o8_sum3=d3+d4;

    wire signed [W+2-1:0] t_o8_y10=1*o8_sum0;
    wire signed [W+2-1:0] A_o8_y10=10*d0+t_o8_y10;
    wire signed [W+2-1:0] B_o8_y10=t_o8_y10-(12)*d7;
    wire signed [W+2-1:0] t_o8_y11=3*o8_sum1;
    wire signed [W+2-1:0] A_o8_y11=8*d1+t_o8_y11;
    wire signed [W+2-1:0] B_o8_y11=(14)*d6-t_o8_y11;
    wire signed [W+2-1:0] t_o8_y12=5*o8_sum2;
    wire signed [W+2-1:0] A_o8_y12=5*d2+t_o8_y12;
    wire signed [W+2-1:0] B_o8_y12=t_o8_y12-(15)*d5;
    wire signed [W+2-1:0] t_o8_y13=7*o8_sum3;
    wire signed [W+2-1:0] A_o8_y13=2*d3+t_o8_y13;
    wire signed [W+2-1:0] B_o8_y13=(16)*d4-t_o8_y13;
    wire signed [W+2-1:0] t_o8_y30=-3*o8_sum0;
    wire signed [W+2-1:0] A_o8_y30=14*d0+t_o8_y30;
    wire signed [W+2-1:0] B_o8_y30=(8)*d7-t_o8_y30;
    wire signed [W+2-1:0] t_o8_y31=-9*o8_sum1;
    wire signed [W+2-1:0] A_o8_y31=16*d1+t_o8_y31;
    wire signed [W+2-1:0] B_o8_y31=t_o8_y31-(-2)*d6;
    wire signed [W+2-1:0] t_o8_y32=-11*o8_sum2;
    wire signed [W+2-1:0] A_o8_y32=12*d2+t_o8_y32;
    wire signed [W+2-1:0] B_o8_y32=(-10)*d5-t_o8_y32;
    wire signed [W+2-1:0] t_o8_y33=-10*o8_sum3;
    wire signed [W+2-1:0] A_o8_y33=5*d3+t_o8_y33;
    wire signed [W+2-1:0] B_o8_y33=t_o8_y33-(-15)*d4;
    wire signed [W+2-1:0] t_o8_y50=5*o8_sum0;
    wire signed [W+2-1:0] A_o8_y50=5*d0+t_o8_y50;
    wire signed [W+2-1:0] B_o8_y50=t_o8_y50-(15)*d7;
    wire signed [W+2-1:0] t_o8_y51=11*o8_sum1;
    wire signed [W+2-1:0] A_o8_y51=-10*d1+t_o8_y51;
    wire signed [W+2-1:0] B_o8_y51=(12)*d6-t_o8_y51;
    wire signed [W+2-1:0] t_o8_y52=7*o8_sum2;
    wire signed [W+2-1:0] A_o8_y52=-16*d2+t_o8_y52;
    wire signed [W+2-1:0] B_o8_y52=t_o8_y52-(-2)*d5;
    wire signed [W+2-1:0] t_o8_y53=-3*o8_sum3;
    wire signed [W+2-1:0] A_o8_y53=-8*d3+t_o8_y53;
    wire signed [W+2-1:0] B_o8_y53=(-14)*d4-t_o8_y53;
    wire signed [W+2-1:0] t_o8_y70=-7*o8_sum0;
    wire signed [W+2-1:0] A_o8_y70=16*d0+t_o8_y70;
    wire signed [W+2-1:0] B_o8_y70=(2)*d7-t_o8_y70;
    wire signed [W+2-1:0] t_o8_y71=-10*o8_sum1;
    wire signed [W+2-1:0] A_o8_y71=5*d1+t_o8_y71;
    wire signed [W+2-1:0] B_o8_y71=t_o8_y71-(-15)*d6;
    wire signed [W+2-1:0] t_o8_y72=3*o8_sum2;
    wire signed [W+2-1:0] A_o8_y72=-14*d2+t_o8_y72;
    wire signed [W+2-1:0] B_o8_y72=(-8)*d5-t_o8_y72;
    wire signed [W+2-1:0] t_o8_y73=11*o8_sum3;
    wire signed [W+2-1:0] A_o8_y73=-10*d3+t_o8_y73;
    wire signed [W+2-1:0] B_o8_y73=t_o8_y73-(12)*d4;

    //8point dct부분
    wire signed [input_BW+3-1:0] ss0,ss1,ss2,ss3;
    wire signed [input_BW+2-1:0] sd0,sd1,sd2,sd3;

    assign ss0=s0+s7; assign sd0=s0-s7;
    assign ss1=s1+s6; assign sd1=s1-s6;
    assign ss2=s2+s5; assign sd2=s2-s5;
    assign ss3=s3+s4; assign sd3=s3-s4;

    //4point odd dct, 여기도 위랑 동일
    wire signed [input_BW+3-1:0] o4_sum0=sd0+sd3;
    wire signed [input_BW+3-1:0] o4_sum1=sd1+sd2;

    wire signed [W+2-1:0] t_o4_y20=2*o4_sum0;
    wire signed [W+2-1:0] A_o4_y20=9*sd0+t_o4_y20;
    wire signed [W+2-1:0] B_o4_y20=t_o4_y20-(13)*sd3;
    wire signed [W+2-1:0] t_o4_y21=6*o4_sum1;
    wire signed [W+2-1:0] A_o4_y21=3*sd1+t_o4_y21;
    wire signed [W+2-1:0] B_o4_y21=(15)*sd2-t_o4_y21;
    wire signed [W+2-1:0] t_o4_y60=-6*o4_sum0;
    wire signed [W+2-1:0] A_o4_y60=15*sd0+t_o4_y60;
    wire signed [W+2-1:0] B_o4_y60=(3)*sd3-t_o4_y60;
    wire signed [W+2-1:0] t_o4_y61=-11*o4_sum1;
    wire signed [W+2-1:0] A_o4_y61=9*sd1+t_o4_y61;
    wire signed [W+2-1:0] B_o4_y61=t_o4_y61-(-13)*sd2;

    //4point dct
    wire signed [input_BW+4-1:0] sss0,sss1;
    wire signed [input_BW+3-1:0] ssd0,ssd1;

    //2point odd dct, 위랑 동일
    assign sss0=ss0+ss3; assign ssd0=ss0-ss3;
    assign sss1=ss1+ss2; assign ssd1=ss1-ss2;

    wire signed [input_BW+4-1:0] o2_sum0=ssd0+ssd1;
    wire signed [W+2-1:0] t_o2_y40=4*o2_sum0;
    wire signed [W+2-1:0] A_o2_y40=6*ssd0+t_o2_y40;
    wire signed [W+2-1:0] B_o2_y40=t_o2_y40-(14)*ssd1;

    wire signed [W-1:0] y0,y1,y2,y3,y4,y5,y6,y7,y8,y9,y10,y11,y12,y13,y14,y15;

    
assign y0 = 8*(sss0+sss1); //2point even dct
    assign y8 = 8*(sss0-sss1); //2point even dct

    assign y1 = A_o8_y10+A_o8_y11+A_o8_y12+A_o8_y13;
    assign y2 = A_o4_y20+A_o4_y21;
    assign y3 = A_o8_y30+A_o8_y31+A_o8_y32+A_o8_y33;
    assign y4 = A_o2_y40;
    assign y5 = A_o8_y50+A_o8_y51+A_o8_y52+A_o8_y53;
    assign y6 = A_o4_y60+A_o4_y61;
    assign y7 = A_o8_y70+A_o8_y71+A_o8_y72+A_o8_y73;
    assign y9 = B_o8_y70+B_o8_y71+B_o8_y72+B_o8_y73;
    assign y10 = B_o4_y60+B_o4_y61;
    assign y11 = B_o8_y50+B_o8_y51+B_o8_y52+B_o8_y53;
    assign y12 = B_o2_y40;
    assign y13 = B_o8_y30+B_o8_y31+B_o8_y32+B_o8_y33;
    assign y14 = B_o4_y20+B_o4_y21;
    assign y15 = B_o8_y10+B_o8_y11+B_o8_y12+B_o8_y13;
    assign x_out = {
        (is_dc | is_dc2) ? y0[14:3] : y0[12:1],
        is_dc ? y1[14:3] : y1[12:1], y2[12:1], y3[12:1],
        y4[12:1], y5[12:1], y6[12:1], y7[12:1],
        y8[12:1], y9[12:1], y10[12:1], y11[12:1],
        y12[12:1], y13[12:1], y14[12:1], y15[12:1]
    };
endmodule

module D_FF128_v6(q, d, clk, rstn);

