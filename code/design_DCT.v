module DCT_1D_1st
#( parameter BW = 8 )

(   input [16*8-1:0] x_in, //unsigned 0~255
    output [16*BW-1:0] x_out
);

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////                  Coefficient                //////////////////
    /////////////////////////////////////////////////////////////////////////////////
    localparam coeffi_quant = 4'd8;

    wire signed [coeffi_quant-1:0] c1,c2,c3,c4,c5,c6,c7,c8,c9,c10,c11,c12,c13,c14,c15;

    // 16-point DCT-II unique coefficients, Q1.7 signed (sign + 7 frac bits)
    //   c_k = (1/sqrt(8)) * cos(k*pi/32),  k = 1..15   (a..o)
    //   stored as positive magnitudes (MSB=0); sign is applied by the
    //   surrounding add/sub matrix structure.  (generated by
    //   gen_DCT_coeffi_verilog.m)
    //   coefficient -> (8.7)
    assign c1  = 8'h2D;  // a = 0.351851 -> 0.351562 (err -0.000288) 
    assign c2  = 8'h2C;  // b = 0.346760 -> 0.343750 (err -0.003010)
    assign c3  = 8'h2B;  // c = 0.338330 -> 0.335938 (err -0.002392)
    assign c4  = 8'h2A;  // d = 0.326641 -> 0.328125 (err +0.001484)
    assign c5  = 8'h28;  // e = 0.311806 -> 0.312500 (err +0.000694)
    assign c6  = 8'h26;  // f = 0.293969 -> 0.296875 (err +0.002906)
    assign c7  = 8'h23;  // g = 0.273300 -> 0.273438 (err +0.000138)
    assign c8  = 8'h20;  // h = 0.250000 -> 0.250000 (err +0.000000)
    assign c9  = 8'h1D;  // i = 0.224292 -> 0.226562 (err +0.002270)
    assign c10 = 8'h19;  // j = 0.196424 -> 0.195312 (err -0.001111)
    assign c11 = 8'h15;  // k = 0.166664 -> 0.164062 (err -0.002601)
    assign c12 = 8'h11;  // l = 0.135299 -> 0.132812 (err -0.002487)
    assign c13 = 8'h0D;  // m = 0.102631 -> 0.101562 (err -0.001069)
    assign c14 = 8'h09;  // n = 0.068975 -> 0.070312 (err +0.001337)
    assign c15 = 8'h04;  // o = 0.034654 -> 0.031250 (err -0.003404)

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////               x preparation                ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [9-1:0] x0,x1,x2,x3,x4,x5,x6,x7,x8,x9,x10,x11,x12,x13,x14,x15; //x div

    // unsigned 9-bit pixel [0,255] -> signed 9-bit [0,255] (zero-extend, no level shift)
    // symmetry pair (x_i, x_{15-i})
    assign x0  = {1'b0, x_in[8*1 -1 : 8*0 ]};
    assign x15 = {1'b0, x_in[8*16-1 : 8*15]};

    assign x1  = {1'b0, x_in[8*2 -1 : 8*1 ]};
    assign x14 = {1'b0, x_in[8*15-1 : 8*14]};

    assign x2  = {1'b0, x_in[8*3 -1 : 8*2 ]};
    assign x13 = {1'b0, x_in[8*14-1 : 8*13]};

    assign x3  = {1'b0, x_in[8*4 -1 : 8*3 ]};
    assign x12 = {1'b0, x_in[8*13-1 : 8*12]};

    assign x4  = {1'b0, x_in[8*5 -1 : 8*4 ]};
    assign x11 = {1'b0, x_in[8*12-1 : 8*11]};

    assign x5  = {1'b0, x_in[8*6 -1 : 8*5 ]};
    assign x10 = {1'b0, x_in[8*11-1 : 8*10]};

    assign x6  = {1'b0, x_in[8*7 -1 : 8*6 ]};
    assign x9  = {1'b0, x_in[8*10-1 : 8*9 ]};

    assign x7  = {1'b0, x_in[8*8 -1 : 8*7 ]};
    assign x8  = {1'b0, x_in[8*9 -1 : 8*8 ]};

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////               s,d preparation              ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [10-1:0] s0,s1,s2,s3,s4,s5,s6,s7; //sum wire .w signed padding 1bit
    wire signed [9-1:0] d0,d1,d2,d3,d4,d5,d6,d7; //diff wire .w auto signed converted

    // butterfly1 : (s_i, d_i) = (x_i + x_{15-i}, x_i - x_{15-i})
    //  s : signed [9:0] (auto sign-extend from x), d : signed [8:0]
    assign s0 = x0 + x15;
    assign d0 = x0 - x15;

    assign s1 = x1 + x14;
    assign d1 = x1 - x14;

    assign s2 = x2 + x13;
    assign d2 = x2 - x13;

    assign s3 = x3 + x12;
    assign d3 = x3 - x12;

    assign s4 = x4 + x11;
    assign d4 = x4 - x11;

    assign s5 = x5 + x10;
    assign d5 = x5 - x10;

    assign s6 = x6 + x9 ;
    assign d6 = x6 - x9 ;

    assign s7 = x7 + x8 ;
    assign d7 = x7 - x8 ;

    /////////////////////////////////////////////////////////////////////////////////
    //////////////////                 y operation                ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    wire signed [18-1:0] y0,y1,y2,y3,y4,y5,y6,y7,y8,y9,y10,y11,y12,y13,y14,y15; //d 곱셈은 17bit도 가능하긴함 -> 최적화 요소

    //butterfly operation

    //----------------------------------------------------------------------------
    //8-point odd part : y_{odd} = sum of c * d  (8 products per row)
    //  coef mapping: a=c1, c=c3, e=c5, g=c7, i=c9, k=c11, m=c13, o=c15
    //----------------------------------------------------------------------------
    // symmetry pair (y_k, y_{16-k})
    assign y1  =  c1*d0 +  c3*d1 +  c5*d2 +  c7*d3 +  c9*d4 + c11*d5 + c13*d6 + c15*d7;
    assign y15 = c15*d0 - c13*d1 + c11*d2 -  c9*d3 +  c7*d4 -  c5*d5 +  c3*d6 -  c1*d7;

    assign y3  =  c3*d0 +  c9*d1 + c15*d2 - c11*d3 -  c5*d4 -  c1*d5 -  c7*d6 - c13*d7;
    assign y13 = c13*d0 -  c7*d1 +  c1*d2 -  c5*d3 + c11*d4 + c15*d5 -  c9*d6 +  c3*d7;

    assign y5  =  c5*d0 + c15*d1 -  c7*d2 -  c3*d3 - c13*d4 +  c9*d5 +  c1*d6 + c11*d7;
    assign y11 = c11*d0 -  c1*d1 +  c9*d2 + c13*d3 -  c3*d4 +  c7*d5 + c15*d6 -  c5*d7;

    assign y7  =  c7*d0 - c11*d1 -  c3*d2 + c15*d3 +  c1*d4 + c13*d5 -  c5*d6 -  c9*d7;
    assign y9  =  c9*d0 -  c5*d1 - c13*d2 +  c1*d3 - c15*d4 -  c3*d5 + c11*d6 +  c7*d7;

    //----------------------------------------------------------------------------
    //8-point even part : 2nd butterfly on s -> (ss, sd)
    //  ss_i = s_i + s_{7-i},  sd_i = s_i - s_{7-i},   i = 0..3
    //----------------------------------------------------------------------------
    wire signed [11-1:0] ss0, ss1, ss2, ss3; // sum  of s pair : [0, 1020]
    wire signed [10-1:0] sd0, sd1, sd2, sd3; // diff of s pair : [-510, 510]

    // butterfly2 : (ss_i, sd_i) = (s_i + s_{7-i}, s_i - s_{7-i})
    assign ss0 = s0 + s7;
    assign sd0 = s0 - s7;

    assign ss1 = s1 + s6;
    assign sd1 = s1 - s6;

    assign ss2 = s2 + s5;
    assign sd2 = s2 - s5;

    assign ss3 = s3 + s4;
    assign sd3 = s3 - s4;

    //----------------------------------------------------------------------------
    //4-point odd part : y_{2,6,10,14} = sum of c * sd  (4 products per row)
    //  coef mapping: b=c2, f=c6, j=c10, n=c14
    //----------------------------------------------------------------------------
    // symmetry pair (y_k, y_{16-k})
    assign y2  =  c2*sd0 +  c6*sd1 + c10*sd2 + c14*sd3;
    assign y14 = c14*sd0 - c10*sd1 +  c6*sd2 -  c2*sd3;

    assign y6  =  c6*sd0 - c14*sd1 -  c2*sd2 - c10*sd3;
    assign y10 = c10*sd0 -  c2*sd1 + c14*sd2 +  c6*sd3;

    //----------------------------------------------------------------------------
    //4-point even part : 3rd butterfly on ss -> (sss, ssd)
    //  sss_i = ss_i + ss_{3-i},  ssd_i = ss_i - ss_{3-i},   i = 0..1
    //----------------------------------------------------------------------------
    wire signed [12-1:0] sss0, sss1; // sum  of ss pair : [0, 2040]
    wire signed [11-1:0] ssd0, ssd1; // diff of ss pair : [-1020, 1020]

    // butterfly3 : (sss_i, ssd_i) = (ss_i + ss_{3-i}, ss_i - ss_{3-i})
    assign sss0 = ss0 + ss3;
    assign ssd0 = ss0 - ss3;

    assign sss1 = ss1 + ss2;
    assign ssd1 = ss1 - ss2;

    //----------------------------------------------------------------------------
    //2-point odd part : y_{4,12} = c * ssd  (2 products per row)
    //  coef mapping: d=c4, l=c12
    //----------------------------------------------------------------------------
    assign y4  =  c4*ssd0 + c12*ssd1;
    assign y12 = c12*ssd0 -  c4*ssd1;

    //----------------------------------------------------------------------------
    //2-point even part : y_{0,8} = h * (sss0 +/- sss1)   (h = c8 = 0.25 exact)
    //----------------------------------------------------------------------------
    assign y0 = c8 * (sss0 + sss1);
    assign y8 = c8 * (sss0 - sss1);


    /////////////////////////////////////////////////////////////////////////////////
    //////////////////              result truncation             ///////////////////
    /////////////////////////////////////////////////////////////////////////////////

    // truncate Q11.7 -> BW bits per output (drop 7 LSB frac, keep BW MSBs of integer).
    // NOTE: BW=8 wraps for |y|>=128 (DC can reach 1020); use BW=11 to capture full int.
    assign x_out = {y0 [7+BW-1:7], y1 [7+BW-1:7],
                    y2 [7+BW-1:7], y3 [7+BW-1:7],
                    y4 [7+BW-1:7], y5 [7+BW-1:7],
                    y6 [7+BW-1:7], y7 [7+BW-1:7],
                    y8 [7+BW-1:7], y9 [7+BW-1:7],
                    y10[7+BW-1:7], y11[7+BW-1:7],
                    y12[7+BW-1:7], y13[7+BW-1:7],
                    y14[7+BW-1:7], y15[7+BW-1:7]};

endmodule