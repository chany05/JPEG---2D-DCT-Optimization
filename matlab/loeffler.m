function x = lee_fct_8pt(X_hat)
    % 입력 X_hat은 e(n)*X(n) 형태로 스케일링된 8x1 주파수 벡터입니다.
    if isrow(X_hat)
        X_hat = X_hat';
    end

    % ---------------------------------------------------------------------
    % Stage 1: 입력 재정렬 (Bit-Reversed Order Input)
    % 논문 Fig. 1 맨 왼쪽의 입력 순서 [0, 4, 2, 6, 1, 5, 3, 7] 매핑
    % ---------------------------------------------------------------------
    in0 = X_hat(1); % X^(0)
    in1 = X_hat(5); % X^(4)
    in2 = X_hat(3); % X^(2)
    in3 = X_hat(7); % X^(6)
    in4 = X_hat(2); % X^(1)
    in5 = X_hat(6); % X^(5)
    in6 = X_hat(4); % X^(3)
    in7 = X_hat(8); % X^(7)

    % ---------------------------------------------------------------------
    % Stage 2: 4포인트 하위 블록 진입 전 연산
    % 짝수단(G)은 그대로 두고, 홀수단(H)은 인접 주파수끼리 미리 더함
    % H(n) = X^(2n+1) + X^(2n-1) 수식 구현 (논문 Eq. 17b)[cite: 2]
    % ---------------------------------------------------------------------
    % 짝수 주파수 그룹 (G)
    g0_0 = in0;
    g0_1 = in1;
    g0_2 = in2;
    g0_3 = in3;
    
    % 홀수 주파수 그룹 (H) -> 곱셈을 줄이기 위해 '선 덧셈' 수행![cite: 2]
    h0_0 = in4;            % X^(1) + X^(-1) -> X^(-1)은 0이므로[cite: 2]
    h0_1 = in5 + in4;      % X^(5) + X^(1)
    h0_2 = in6 + in5;      % X^(3) + X^(5)
    h0_3 = in7 + in6;      % X^(7) + X^(3)

    % ---------------------------------------------------------------------
    % Stage 3: 하위 4포인트 IDCT 내부 나비 연산 (Butterfly)
    % ---------------------------------------------------------------------
    % G 그룹 4pt 연산
    g1_0 = g0_0 + g0_1;
    g1_1 = g0_0 - g0_1;
    g1_2 = g0_2;
    g1_3 = g0_3;
    
    g2_0 = g1_0 + g1_2;
    g2_1 = g1_1 + g1_3;
    g2_2 = g1_0 - g1_2;
    g2_3 = g1_1 - g1_3;
    
    % H 그룹 4pt 연산
    h1_0 = h0_0 + h0_1;
    h1_1 = h0_0 - h0_1;
    h1_2 = h0_2;
    h1_3 = h0_3;
    
    h2_0 = h1_0 + h1_2;
    h2_1 = h1_1 + h1_3;
    h2_2 = h1_0 - h1_2;
    h2_3 = h1_1 - h1_3;

    % ---------------------------------------------------------------------
    % Stage 4: 4포인트 IDCT 내부 코사인 곱셈단
    % 고속 처리를 위해 각 하위 단의 특정 분기에 코사인 계수 곱셈 실행[cite: 2]
    % ---------------------------------------------------------------------
    c4_1 = cos(pi / 4);
    c8_1 = cos(pi / 8);
    c8_3 = cos(3 * pi / 8);

    g3_0 = g2_0;
    g3_1 = g2_1;
    g3_2 = g2_2 * c4_1;
    g3_3 = g2_3 * c4_1;
    
    h3_0 = h2_0;
    h3_1 = h2_1;
    h3_2 = h2_2 * c4_1;
    h3_3 = h2_3 * c4_1;

    % ---------------------------------------------------------------------
    % Stage 5: 4포인트 블록 탈출 및 교차 Butterfly
    % ---------------------------------------------------------------------
    g4_0 = g3_0 + g3_3;
    g4_1 = g3_1 + g3_2;
    g4_2 = g3_1 - g3_2;
    g4_3 = g3_0 - g3_3;
    
    h4_0 = h3_0 + h3_3;
    h4_1 = h3_1 + h3_2;
    h4_2 = h3_1 - g3_2; % 흐름도상 교차 감산
    h4_3 = h3_0 - h3_3;

    % ---------------------------------------------------------------------
    % Stage 6: 최종 출력단 및 고정 코사인 역산 (Scaling)
    % 2단계에서 홀수단을 깨부수기 위해 유도했던 고정 코사인 계수 분할 처리[cite: 2]
    % 1 / (2 * cos(angle)) 연산 수행 (논문 Eq. 19)[cite: 2]
    % ---------------------------------------------------------------------
    c16_1 = cos(1 * pi / 16);
    c16_3 = cos(3 * pi / 16);
    c16_5 = cos(5 * pi / 16);
    c16_7 = cos(7 * pi / 16);

    % 홀수단 덩어리에 최종 스케일 역산 곱셈[cite: 2]
    h_final0 = h4_0 * (1 / (2 * c16_1));
    h_final1 = h4_1 * (1 / (2 * c16_3));
    h_final2 = h4_2 * (1 / (2 * c16_5));
    h_final3 = h4_3 * (1 / (2 * c16_7));

    % 짝수단(g)과 최종 보정된 홀수단(h_final)을 더하고 빼서 최종 출력 공간 완성[cite: 2]
    x = zeros(8, 1);
    x(1) = g4_0 + h_final0; % x(0)
    x(2) = g4_1 + h_final1; % x(1)
    x(3) = g4_2 + h_final2; % x(2)
    x(4) = g4_3 + h_final3; % x(3)
    x(5) = g4_3 - h_final3; % x(4)
    x(6) = g4_2 - h_final2; % x(5)
    x(7) = g4_1 - h_final1; % x(6)
    x(8) = g4_0 - h_final0; % x(7)
    
    % 논문 Fig. 1 맨 오른쪽의 출력 비선형 시퀀스 순서대로 정렬[cite: 2]
    % 출력 순서: x(0), x(1), x(3), x(2), x(7), x(6), x(4), x(5)[cite: 2]
    x_ordered = zeros(8, 1);
    x_ordered(1) = x(1); % x(0)
    x_ordered(2) = x(2); % x(1)
    x_ordered(3) = x(4); % x(3)
    x_ordered(4) = x(3); % x(2)
    x_ordered(5) = x(8); % x(7)
    x_ordered(6) = x(7); % x(6)
    x_ordered(7) = x(5); % x(4)
    x_ordered(8) = x(6); % x(5)
    x = x_ordered;
end

clear; clc;

% 1. 테스트용 임의의 DCT 주파수 계수 생성
Y_test = [150.6137, -28.8495, -14.9134, -33.4669, -6.3640, -36.0396, 4.6466, 51.9983]';

% 매틀랩 내장 idct를 위한 표준 입력 스케일링 복원
% (내장 idct 연산 규격에 맞추기 위해 e(n) 계수를 전처리합니다)
X_hat = Y_test;
X_hat(1) = X_hat(1) * (1 / sqrt(2)); 
X_hat = X_hat * sqrt(2 / 8); 

% 2. 매틀랩 표준 내장 IDCT 결과
x_matlab = idct(Y_test);

% 3. 이병기 교수 고속 알고리즘(FCT) 결과 
x_lee_fct = lee_fct_8pt(X_hat);

% 결과 출력 및 비교
fprintf('--- 이병기 교수 FCT (IDCT) 결과 비교 ---\n');
disp('Index | Matlab 내장 IDCT | 이병기 교수 FCT');
disp('-----------------------------------------------');
for i = 1:8
    fprintf('  %d   |     %8.4f     |    %8.4f\n', i-1, x_matlab(i), x_lee_fct(i));
end

% 오차(Error) 계산
error = norm(x_matlab - x_lee_fct);
fprintf('\n두 결과의 오차(Norm): %e\n', error);